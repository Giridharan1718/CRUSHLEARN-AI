// AdaptiveLearningService: adapter over the existing bounded adaptive loop.
//
// The loop itself is deterministic and lives in src/intelligence. This service
// gives it the shared contract and keeps its measured evidence, assumptions and
// uncertainties separate.

import { runAdaptiveLoop } from '../intelligence/adaptiveLoop.mjs';
import { selectNextAction } from '../intelligence/learningContext.mjs';
import {
  CAPABILITY_STATUS,
  RUN_STATUS,
  createServiceResult,
  failureResult,
} from './contracts.mjs';

export const ADAPTIVE_LEARNING_CAPABILITY = CAPABILITY_STATUS.PARTIAL;

export function planNextLearningAction({
  answer = null,
  practice = null,
  practiceResult = null,
  relatedVisual = null,
  readySourceCount = 0,
} = {}) {
  return selectNextAction({
    answer,
    practice,
    practiceResult,
    relatedVisual,
    readySourceCount,
  });
}

export async function runAdaptiveLearning(request = {}) {
  const started = Date.now();
  if (!request.userId || !request.notebookId) {
    return failureResult(
      'adaptive_learning',
      ['Adaptive practice needs a signed-in learner and a notebook.'],
      {
        capability: ADAPTIVE_LEARNING_CAPABILITY,
        unavailable: ['adaptive practice without notebook context'],
      }
    );
  }

  const event =
    request.event ||
    (request.response
      ? { type: 'practice_response', response: request.response }
      : { type: 'question', question: request.question });

  const result = await runAdaptiveLoop({
    event,
    userId: request.userId,
    notebookId: request.notebookId,
    sources: request.sources,
    sourceContents: request.sourceContents,
    previousContext: request.previousContext,
    signal: request.signal,
    limits: request.limits,
  });

  const status =
    result.status === 'cancelled'
      ? RUN_STATUS.FAILED
      : result.status === 'blocked'
        ? RUN_STATUS.BLOCKED
        : result.status === 'complete'
          ? RUN_STATUS.COMPLETED
          : RUN_STATUS.PARTIAL;

  return createServiceResult({
    service: 'adaptive_learning',
    capability: ADAPTIVE_LEARNING_CAPABILITY,
    status,
    data: result,
    evidence: (result.adaptive?.sourceFacts || []).map((fact) => ({
      kind: 'source_evidence',
      sourceId: fact.sourceId,
      sourceTitle: fact.sourceTitle,
      page: fact.page,
      quote: fact.quote,
      citation: fact.citation,
    })),
    learnerEvidence: (result.adaptive?.assessmentEvidence || []).map((item) => ({
      kind: 'learner_evidence',
      text: item.practiceId,
      correctness: item.correct,
      note: 'One recall check recorded by the adaptive loop.',
    })),
    hypotheses: (result.adaptive?.hypotheses || []).map((item) => ({
      kind: 'unverified_hypothesis',
      text: item.text,
    })),
    interpretations: (result.adaptive?.generatedExplanations || []).map((item) => ({
      kind: 'rule_based_interpretation',
      text: item.text,
      note: 'Generated by a deterministic rule from a verified source passage.',
    })),
    limitations: [
      ...(result.adaptive?.assumptions || []),
      ...(result.adaptive?.uncertainties || []),
    ],
    errors: result.errorCode ? [result.errorCode] : [],
    metrics: {
      latencyMs: Date.now() - started,
      steps: result.report?.logs?.length || 0,
      retrievalCalls: (result.report?.logs || []).filter((log) =>
        String(log.action || '').includes('retrieve')
      ).length,
    },
    generator: 'local_deterministic',
  });
}
