import { useState } from 'react';
import {
  CITATION_LOCATOR_KINDS,
  formatCitationLabel,
} from '../../notebooks/citations.mjs';
import { formatGeneratorLabel } from '../../notebooks/generators.mjs';
import { SOURCE_STATUSES } from '../../notebooks/sourceSchema.mjs';
import ExplanationPanel from './ExplanationPanel';

const ROLE_LABELS = {
  user: 'You',
  assistant: 'Assistant',
  system: 'System',
};

const ChatPanel = ({
  messages = [],
  sources = [],
  sourceContents = {},
  notebookId = '',
  userId = '',
  onSaveNote,
  onAsk,
  onInspectCitation,
  gatewayStatus = null,
}) => {
  const sourceById = new Map(sources.map((source) => [source.id, source]));
  const [savedMessageIds, setSavedMessageIds] = useState(() => new Set());
  const [saveErrors, setSaveErrors] = useState({});
  const [explainMessageId, setExplainMessageId] = useState(null);
  const [question, setQuestion] = useState('');
  const [pending, setPending] = useState(false);
  const [askError, setAskError] = useState('');
  const [askStatus, setAskStatus] = useState('');

  const readySourceCount = sources.filter(
    (source) =>
      source?.status === SOURCE_STATUSES.READY && source.hasExtractedText
  ).length;

  const gatewayReady = Boolean(
    gatewayStatus?.available && gatewayStatus?.providerConfigured
  );

  /**
   * A chat message is only treated as source-grounded when its content is an
   * exact stored citation quote; otherwise the explanation is honest about
   * being based on the message text itself.
   */
  const explainSelectionFor = (message) => {
    const citation = (message.citations || []).find((item) =>
      sourceById.has(item.sourceId)
    );
    const isExactQuote =
      Boolean(citation) &&
      citation.quote === message.content &&
      citation.locator?.kind === CITATION_LOCATOR_KINDS.OFFSET;

    if (!isExactQuote) {
      return { text: message.content, sourceId: '', sourceTitle: '', page: null, selectionStart: null };
    }
    return {
      text: message.content,
      sourceId: citation.sourceId,
      sourceTitle: sourceById.get(citation.sourceId)?.title || '',
      page: Number.isInteger(citation.page) ? citation.page : null,
      selectionStart: citation.locator.start,
    };
  };

  const handleSaveMessage = async (message) => {
    if (!onSaveNote || savedMessageIds.has(message.id)) return;
    const result = await onSaveNote({
      title: 'Saved from chat history',
      body: message.content,
      citations: message.citations || [],
      messageId: message.id,
    });
    if (result?.ok) {
      setSavedMessageIds(
        (current) => new Set([...current, message.id])
      );
      setSaveErrors((current) => {
        const next = { ...current };
        delete next[message.id];
        return next;
      });
    } else {
      setSaveErrors((current) => ({
        ...current,
        [message.id]: result?.errors?.[0] || 'The note could not be saved.',
      }));
    }
  };

  const handleSubmit = async (event) => {
    event.preventDefault();
    const trimmed = question.trim();
    if (!trimmed || pending || !onAsk) return;

    setPending(true);
    setAskError('');
    setAskStatus('');

    try {
      const result = await onAsk(trimmed);
      if (result && result.ok === false) {
        setAskError(result.errors?.[0] || 'The question could not be answered.');
      } else {
        setAskStatus(
          `Answer added from ${formatGeneratorLabel(
            result?.result?.generator
          )}. Every quotation is checked against stored source text.`
        );
      }
      setQuestion('');
    } catch (error) {
      setAskError(error?.message || 'The question could not be answered.');
    } finally {
      setPending(false);
    }
  };

  return (
    <section
      aria-labelledby="chat-history-heading"
      className="rounded-2xl border border-line bg-surface p-6 shadow-sm"
    >        <h2 id="chat-history-heading" className="text-lg font-semibold text-ink">
        Chat with your sources
      </h2>
      <p className="mt-1 text-sm text-ink-muted">
        Ask a question and the answer is built only from the passages in this
        notebook. This build is not connected to an AI provider by default.
        Every citation is checked against the stored source text before it is
        shown.
      </p>

      <div
        className={`mt-4 rounded-lg border p-3 text-sm ${
          gatewayReady
            ? 'border-success/40 bg-success-soft text-success'
            : 'border-warning/40 bg-warning-soft text-warning'
        }`}
      >
        {gatewayReady ? (
          <>
            The AI gateway is running on {gatewayStatus.model}. Answers are
            generated by a model and re-checked against your sources.
          </>
        ) : (
          <>
            The AI gateway is not available
            {gatewayStatus?.available
              ? ' because no provider key is configured on it'
              : ''}
            . Answers here are direct quotations from your sources, not
            AI-generated explanations.
          </>
        )}
      </div>

      {onAsk && (
        <form className="mt-4" onSubmit={handleSubmit}>
          <label
            htmlFor="chat-question-input"
            className="text-sm font-semibold text-ink"
          >
            Ask a question about your sources
          </label>
          <textarea
            id="chat-question-input"
            value={question}
            onChange={(event) => setQuestion(event.target.value)}
            rows={2}
            disabled={pending || readySourceCount === 0}
            placeholder={
              readySourceCount === 0
                ? 'Add a source with readable text first.'
                : 'What does this source say about…'
            }
            className="mt-2 w-full rounded-lg border border-line bg-surface p-3 text-sm text-ink placeholder:text-ink-subtle disabled:cursor-not-allowed disabled:bg-line-subtle"
          />
          <div className="mt-2 flex items-center gap-3">
            <button
              type="submit"
              disabled={pending || !question.trim() || readySourceCount === 0}
              className="rounded-lg bg-primary-600 px-4 py-2 text-sm font-semibold text-ink-inverse transition hover:bg-primary-700 disabled:cursor-not-allowed disabled:bg-line"
            >
              {pending ? 'Asking…' : 'Ask'}
            </button>
            {readySourceCount === 0 && (
              <p className="text-xs text-ink-muted">
                Add a source with readable text to ask a question.
              </p>
            )}
          </div>
          {askError && (
            <p role="alert" className="mt-2 text-xs text-danger">
              {askError}
            </p>
          )}
          {pending ? (
            <p role="status" className="mt-2 text-xs text-info">
              Searching the stored sources and checking every citation…
            </p>
          ) : null}
          {askStatus ? (
            <p role="status" className="mt-2 text-xs text-success">
              {askStatus}
            </p>
          ) : null}
        </form>
      )}

      {messages.length === 0 ? (
        <div className="mt-5 rounded-xl border border-dashed border-line p-8 text-center">
          <p className="text-3xl mb-2" aria-hidden="true">
            💬
          </p>
          <h3 className="font-semibold text-ink">No chat messages yet</h3>
          <p className="mt-1 text-sm text-ink-muted">
            Ask a question above. Your question and the answer are stored in
            this browser only.
          </p>
        </div>
      ) : (
        <ol className="mt-5 space-y-4">
          {messages.map((message) => {
            const citations = (message.citations || []).filter((citation) =>
              sourceById.has(citation.sourceId)
            );

            return (
              <li
                key={message.id}
                className={`rounded-xl border p-4 ${
                  message.role === 'assistant'
                    ? 'border-primary-100 bg-primary-50'
                    : 'border-line bg-line-subtle'
                }`}
              >
                <p className="text-xs font-semibold uppercase tracking-wide text-ink-subtle">
                  {ROLE_LABELS[message.role] || message.role}
                </p>
                <p className="mt-2 whitespace-pre-wrap text-sm text-ink">
                  {message.content}
                </p>

                {onSaveNote && (
                  <div className="mt-2">
                    <button
                      type="button"
                      onClick={() => handleSaveMessage(message)}
                      disabled={savedMessageIds.has(message.id)}
                      className="text-xs font-medium text-accent-strong underline-offset-2 transition hover:underline disabled:cursor-not-allowed disabled:text-ink-subtle disabled:no-underline"
                    >
                      {savedMessageIds.has(message.id) ? 'Saved to notes ✓' : 'Save as note'}
                    </button>
                    {saveErrors[message.id] && (
                      <p role="alert" className="mt-1 text-xs text-danger">
                        {saveErrors[message.id]}
                      </p>
                    )}
                  </div>
                )}

                <div className="mt-2">
                  <button
                    type="button"
                    aria-pressed={explainMessageId === message.id}
                    onClick={() =>
                      setExplainMessageId((current) =>
                        current === message.id ? null : message.id
                      )
                    }
                    className="text-xs font-medium text-accent-strong underline-offset-2 transition hover:underline"
                  >
                    {explainMessageId === message.id
                      ? 'Hide explanation'
                      : 'Explain simply'}
                  </button>
                  {explainMessageId === message.id && (
                    <ExplanationPanel
                      selection={explainSelectionFor(message)}
                      sourceTexts={sourceContents}
                      notebookId={notebookId}
                      userId={userId}
                    />
                  )}
                </div>

                {citations.length > 0 && (
                  <div className="mt-3 space-y-2">
                    <p className="text-xs font-semibold text-ink-muted">
                      Sources cited
                    </p>
                    {citations.map((citation, index) => (
                      <blockquote
                        key={`${message.id}-citation-${index}`}
                        className="rounded-lg border border-line bg-surface p-3 text-sm"
                      >
                        <p className="text-xs font-semibold text-primary-700">
                          {formatCitationLabel(
                            citation,
                            sourceById.get(citation.sourceId)
                          )}
                        </p>
                        <p className="mt-1 text-ink-muted">“{citation.quote}”</p>
                        {typeof onInspectCitation === 'function' ? (
                          <button
                            type="button"
                            onClick={() => onInspectCitation(citation)}
                            className="mt-2 rounded-lg border border-line px-2.5 py-1.5 text-xs font-semibold text-ink-muted hover:bg-line-subtle focus:outline-none focus:ring-2 focus:ring-accent/30"
                          >
                            Inspect exact quotation
                          </button>
                        ) : null}
                      </blockquote>
                    ))}
                  </div>
                )}
              </li>
            );
          })}
        </ol>
      )}
    </section>
  );
};

export default ChatPanel;
